#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const source=fs.readFileSync(new URL('../functions/command_center_mcp.js',import.meta.url),'utf8');
const homeSource=fs.readFileSync(new URL('../functions/home_center_mcp.js',import.meta.url),'utf8');
const publicManifest=fs.readFileSync(new URL('../contracts/home-center-public-tool-manifest.v1.json',import.meta.url),'utf8');
const {COMMAND_CENTER_COLLECTIONS,COMMAND_CENTER_BUCKET_KINDS,COMMAND_CENTER_BUCKET_LAYOUT,createCommandCenterMcpServer,commandCenterCapabilitiesPayload}=require('../functions/command_center_mcp.js');
const admin={firestore(){return {};}};
const server=createCommandCenterMcpServer({admin});
const names=Object.keys(server._registeredTools).sort();
assert(names.includes('command_center.health'));
assert(names.includes('command_center.readiness'));
assert(names.includes('command_center.capabilities'));
assert(names.includes('command_center_operation'));
assert.doesNotMatch(homeSource, /jobs\.create|jobs\.get_events|jobs\.get_artifacts|jobs\.answer_question|jobs\.authorize_mutation/, "top-level Command Center tool must not advertise retired execution");
assert.doesNotMatch(source, /\bjobId\b/, 'retained Command Center source must not expose legacy job identity');
assert.doesNotMatch(homeSource, /jobId: 'optional string'/, 'Home registry must not advertise legacy Command Center job identity');
assert.doesNotMatch(publicManifest, /Command Center Codex|Cloud Blender|jobs\.create|jobId/, 'public MCP catalog must not advertise retired Command Center execution');
assert(names.includes('command_center.bucket.get_layout'));
assert(names.includes('command_center.browser_sessions.create'));
assert.equal(names.some((name)=>name.startsWith('command_center.agents.')),false,'Codex agents remain discoverable');
assert.equal(names.some((name)=>name.startsWith('command_center.workers.')),false,'Codex workers remain discoverable');
assert.equal(names.some((name)=>name.startsWith('command_center.hosts.')),false,'Codex worker host aliases remain discoverable');
for (const prefix of ['command_center.jobs.','command_center.machine_images.','command_center.provisioning.','command_center.codex_sessions.','command_center.routing.','command_center.proof.']) assert.equal(names.some((name)=>name.startsWith(prefix)),false,prefix+' remains discoverable');
assert.equal(names.some((name)=>name.startsWith('command_center.render.')),false,'retired renderer remains discoverable');
assert.equal(COMMAND_CENTER_COLLECTIONS.renderRequests,undefined);
assert.equal(COMMAND_CENTER_BUCKET_LAYOUT.bucketId,'command-center');
assert(COMMAND_CENTER_BUCKET_KINDS.includes('memory.current_condensed'));
const capabilities=commandCenterCapabilitiesPayload(server);
assert.deepEqual(capabilities.topLevelTools,names);
assert.equal(JSON.stringify(capabilities).includes('blender'),false);
assert.match(source,/capability_retired\.use_blender_workspace/);
assert.match(source,/capability_retired\.command_center_codex/);
assert.match(homeSource,/capability_retired\.use_blender_workspace/);
assert.match(homeSource,/capability_retired\.command_center_codex/);
assert.doesNotMatch(source,/server\.registerTool\('command_center\.(?:agents|workers|hosts|jobs|machine_images|provisioning|codex_sessions|routing|proof|render)\./);
assert.doesNotMatch(homeSource,/^\s*'(?:agents|workers|render\.)\./m);
for(const path of ['../cloud-worker','deploy_command_center_cloud_worker.sh','codex_cloud_bridge.mjs']) assert.equal(fs.existsSync(new URL(path,import.meta.url)),false,path+' must remain deleted');
console.log(JSON.stringify({ok:true,toolCount:names.length,retired:['command_center_codex','cloud_blender'],remainingControlSurfaces:['bucket','app_control','browser','projects']},null,2));
